//! Snapshot copies of already-converted, native-owned dictionaries.
//!
//! This pilot deliberately keeps ownership in V8 private slots. Dictionary and
//! sequence containers are copied, while interface leaves keep their identity
//! and remain traced by V8. It does not turn scoped handles into Rust-owned
//! state: doing that needs an explicit rooting/teardown policy and cannot be
//! inferred from a raw converter or an interface's WebIDL name.
//!
//! RTCConfiguration therefore stays attached to its receiver, including when a
//! method from another Realm is borrowed. A CommonRuntimeState map is useful
//! for native payloads such as codecs, but a map holding Global<Object> leaves
//! would root certificate -> connection cycles. Moving these dictionaries there
//! would also require receiver-owner lookup, weak/finalizer cleanup, and isolate
//! teardown ordering. Native certificate handles need a real native payload and
//! wrapper identity policy first; this pilot adds neither a store nor globals.
//!
//! `to_js_snapshot` copies canonical binding output, not arbitrary JS input or
//! Rust values. Binding remains the declaration layer's job. An `into_native`
//! derive is deferred until field ownership policies (including custom raw
//! converters) can be expressed without guessing or generating a parallel Rust
//! type/lifetime graph. Only RTCConfiguration and its nested ICE server opt in.

use moli_v8_util::{new_null_prototype_object, v8str};

/// Prototype policy for every dictionary in a snapshot, including nested ones.
#[derive(Clone, Copy)]
pub enum SnapshotPrototype {
    /// Internal records must not consult author-modifiable Object.prototype.
    Null,
    /// Public snapshots use the current (callee) Realm's Object.prototype.
    Ordinary,
}

/// Copy policy for the canonical JS representation of a converted member.
#[derive(Clone, Copy)]
pub enum SnapshotKind {
    /// Immutable scalar values or interface objects whose identity is retained.
    Identity,
    Sequence(&'static SnapshotKind),
    Dictionary(&'static [SnapshotMember]),
}

/// A member generated from the same metadata as dictionary argument conversion.
pub struct SnapshotMember {
    pub name: &'static str,
    pub kind: SnapshotKind,
    pub optional: bool,
}

/// Explicit snapshot policy for custom raw converters.
///
/// Raw conversion can produce a scalar, an interface, or a canonical container;
/// its representation cannot safely be inferred by the dictionary derive.
pub trait WebIdlSnapshotValue {
    const SNAPSHOT_KIND: SnapshotKind;
}

/// Opt-in dictionary copy metadata, generated by `#[webidl(snapshot)]`.
///
/// Sources must be fresh native binding output or private snapshots, with own
/// data properties and dense arrays. This is not WebIDL input conversion and
/// must never be applied directly to an author-supplied dictionary. It ignores
/// absent optional members and unknown properties, without consulting iterators
/// or prototypes. Missing non-optional members fail instead of silently losing
/// a field when a binding declaration is incomplete.
pub trait WebIdlDictionarySnapshot {
    const SNAPSHOT_MEMBERS: &'static [SnapshotMember];

    fn to_js_snapshot<'s>(
        scope: &mut v8::PinScope<'s, '_>,
        source: v8::Local<'s, v8::Object>,
        prototype: SnapshotPrototype,
    ) -> Option<v8::Local<'s, v8::Object>> {
        copy_dictionary(scope, source, Self::SNAPSHOT_MEMBERS, prototype)
    }
}

fn copy_dictionary<'s>(
    scope: &mut v8::PinScope<'s, '_>,
    source: v8::Local<'s, v8::Object>,
    members: &'static [SnapshotMember],
    prototype: SnapshotPrototype,
) -> Option<v8::Local<'s, v8::Object>> {
    let output = match prototype {
        SnapshotPrototype::Null => new_null_prototype_object(scope),
        SnapshotPrototype::Ordinary => v8::Object::new(scope),
    };
    for member in members {
        let key = v8str(scope, member.name);
        if !source.has_own_property(scope, key.into())? {
            if member.optional {
                continue;
            }
            return None;
        }
        let value = source.get(scope, key.into())?;
        let value = member.kind.copy(scope, value, prototype)?;
        if !output.create_data_property(scope, key.into(), value)? {
            return None;
        }
    }
    Some(output)
}

impl SnapshotKind {
    fn copy<'s>(
        &self,
        scope: &mut v8::PinScope<'s, '_>,
        source: v8::Local<'s, v8::Value>,
        prototype: SnapshotPrototype,
    ) -> Option<v8::Local<'s, v8::Value>> {
        match self {
            Self::Identity => Some(source),
            Self::Sequence(item_kind) => {
                let source = v8::Local::<v8::Array>::try_from(source).ok()?;
                let mut items = Vec::with_capacity(source.length() as usize);
                for index in 0..source.length() {
                    let item = source.get_index(scope, index)?;
                    items.push(item_kind.copy(scope, item, prototype)?);
                }
                Some(v8::Array::new_with_elements(scope, &items).into())
            }
            Self::Dictionary(members) => {
                let source = v8::Local::<v8::Object>::try_from(source).ok()?;
                copy_dictionary(scope, source, members, prototype).map(Into::into)
            }
        }
    }
}
